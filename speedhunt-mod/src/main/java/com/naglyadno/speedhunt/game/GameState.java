package com.naglyadno.speedhunt.game;

/** Состояние текущего матча Speedhunt. */
public enum GameState {
	/** Ждём игроков / команду /speedhunt start. */
	WAITING,
	/** Роли уже выбраны сервером, но игрокам ещё не показаны (пауза-интрига). */
	ASSIGNING,
	/** Роли показаны, идёт отсчёт неприкосновенности — охотники не могут бить. */
	GRACE,
	/** Матч идёт полным ходом. */
	RUNNING,
	/** Матч завершён, показываем результат, скоро автосброс. */
	ENDED
}
